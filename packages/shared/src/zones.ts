import { z } from 'zod';

import { armorClassSchema, traitIdSchema, weaponClassSchema } from './combat.js';
import { zoneIdSchema } from './battle.js';

/**
 * Зоны и монстры. GDD §7.3, §7.4, §7.5.
 *
 * МОНСТРЫ — ДАННЫЕ, НЕ КОД. Та же дисциплина, что с ригами и палитрой:
 * новый монстр — это запись в `packages/data`, включая ссылку на его
 * силуэт. В коде нет ни одного имени монстра и ни одного его числа.
 *
 * Здесь только формы. Числа — в `packages/data/zones.json`
 * и `monsters.json`, кривая роста — в `balance.json` (инвариант 5).
 */

/* ──────────────────────────────── зона ───────────────────────────────── */

export const zoneSpecSchema = z.object({
  id: zoneIdSchema,
  /**
   * Диапазон уровней зоны, [мин, макс]. GDD §7.4.
   *
   * ОПИСАТЕЛЬНОЕ поле: подпись на карточке и рамка, внутри которой
   * лежат участки. Уровень врага он больше НЕ ограничивает — ограничивать
   * нечего, уровень приходит из участка и от игрока не зависит.
   *
   * Что участки покрывают диапазон и не выходят за него, проверяет тест:
   * два описания одного и того же обязаны сходиться.
   */
  levels: z.tuple([z.int().min(1), z.int().min(1)]),
  /**
   * ЧЕТЫРЕ УЧАСТКА С ФИКСИРОВАННЫМИ УРОВНЯМИ МОНСТРОВ. [мин, макс] каждый.
   *
   * Это ответ на тупик из PLAYTEST 2026-09-04. Прежде уровень врага
   * считался как `clamp(уровень игрока + сдвиг, мин, макс)`: игрок рос,
   * зона росла с ним, а снаряжение оставалось того уровня, на котором
   * добыто. Чтобы одеться, надо было убивать тех, кого убить уже
   * не выходило, и выхода средствами игры из этого не было.
   *
   * Теперь уровень врага не зависит от игрока НИКАК. Пройденный участок
   * остаётся проходимым навсегда, а за высоким ilvl надо идти дальше,
   * а не перерастать место, где стоишь.
   */
  segments: z
    .array(
      z.object({
        /** Границы уровней участка, [мин, макс]. */
        levels: z.tuple([z.int().min(1), z.int().min(1)]),
        /**
         * Множитель силы врагов ЭТОГО участка. ОТДЕЛЬНО от уровня.
         *
         * Живёт у участка, а не у зоны, и это следствие замера.
         * С одним числом на зону трудность внутри неё шла не туда:
         * в Пустошах падала на 44 п.п. за две ступени, а в Катакомбах
         * и Кузне РОСЛА — четвёртый участок был легче первого. Причина
         * не в числе, а в его размерности: кривая монстров и снаряжение
         * игрока растут с разными наклонами, и одно число на четыре
         * ступени этого не выражает.
         *
         * Второго такого числа у зоны НЕТ намеренно: две копии одной
         * величины — это место, где они разойдутся.
         */
        power: z.number().positive(),
      }),
    )
    .length(4),
  /**
   * Преобладающий класс брони врагов. GDD §7.4.
   *
   * Это РАБОЧИЙ РЫЧАГ, а не описание: через таблицу матчапов §4.3 он
   * решает, каким оружием сюда идти. Показывается игроку на входе
   * явной плашкой — «ничего не спрятано».
   *
   * Отдельные монстры могут отличаться; что большинство пула совпадает
   * с этим полем, проверяет тест — иначе плашка врала бы.
   *
   * `mixed` — у зоны нет преобладающего класса (§7.4 про пятую зону:
   * «смешанные»). Это не отсутствие значения, а самостоятельный случай:
   * плашка тогда показывает матчап ПО КАЖДОМУ монстру, а не одно число.
   * Что пул при этом действительно разнороден, проверяет тест — иначе
   * «смешанные» врало бы в другую сторону.
   */
  armorClass: z.union([armorClassSchema, z.literal('mixed')]),
  /** Ключи обычных монстров. Бой выбирает из них броском. */
  monsters: z.array(z.string().min(1)).min(1),
  /** Ключ босса — пятый бой зоны. GDD §7.5. */
  boss: z.string().min(1),
  /**
   * Сколько максимума возвращается между боями. Доля, §7.2.
   *
   * ВЕЛИЧИНА ЗОНЫ, а не одна на игру, и это замер, а не вкус. При общей
   * четверти свежий изгнанный доходил до первого решения об эвакуации
   * в 2.8% забегов: он не проигрывал рейд, он его не видел. Кривая зон
   * 85/75/65/55/45% выверена ПРИ РАВНОМ СНАРЯЖЕНИИ, а у него снаряжения
   * нет, и переносимый HP превращает второй бой в почти безнадёжный.
   *
   * Лечится первой зоной, а не всей игрой: дальше игрок приходит
   * снаряжённым, и там четверть — это ставка, ради которой рейд написан.
   *
   * Не задано — берётся `balance.raid.hpRestoreBetweenFights`.
   */
  hpRestoreBetweenFights: z.number().min(0).max(1).optional(),
});
export type ZoneSpec = z.infer<typeof zoneSpecSchema>;

/* ─────────────────────────────── монстр ──────────────────────────────── */

/**
 * Множители к базовой кривой из `balance.monsters`.
 *
 * Множители, а не абсолютные числа: кривая роста одна на всех, и правка
 * её не требует обхода двадцати записей. Монстр задаёт НАКЛОН, а не
 * значения — иначе первый же сдвиг прогрессии рассинхронил бы зоны.
 */
const multipliers = z.object({
  atk: z.number().positive(),
  def: z.number().positive(),
  agi: z.number().positive(),
  spd: z.number().positive(),
});

export const monsterSpecSchema = z.object({
  /** Уникален в пределах игры. Совпадает с ключом локали `monster.<key>`. */
  key: z.string().min(1),
  zone: zoneIdSchema,
  /**
   * Силуэт. Форм четыре на два десятка монстров, и это решение:
   * различать врага надо силуэтом с одного взгляда, а двадцать похожих
   * человекоподобных фигур не различались бы вовсе.
   */
  rig: z.string().min(1),
  /**
   * Подмена цветов рига: ключ палитры → ключ палитры. ART-BIBLE §3.
   *
   * Кто есть кто ВНУТРИ формы, говорит цвет. Подмена по ключу, а не
   * по хексу: цвет мимо палитры — это ассет, про который забыли.
   */
  recolor: z.record(z.string().min(1), z.string().min(1)).optional(),
  /** У монстра класс всегда конкретный: «смешанный» бывает у ЗОНЫ, не у него. */
  armorClass: armorClassSchema,
  weaponClass: weaponClassSchema,
  /** Босс зоны. Пятый бой, две ломающие расчёт механики (§7.5). */
  boss: z.boolean().default(false),
  stats: multipliers,
  /** Множитель брони к кривой. */
  armor: z.number().min(0),
  /** Множители к базовому оружию из `balance.monsters.weapon`. */
  weapon: z.object({ dmgMin: z.number().positive(), dmgMax: z.number().positive() }),
  /**
   * Трейты монстра — те же хуки, что у игрока. GDD §4.5.
   *
   * Механики босса из §7.5 тоже трейты, а не ветки в `resolve.ts`:
   * там не упомянут по имени ни один трейт и ни один статус, и заводить
   * `if (isBoss)` значило бы сломать ровно то свойство, ради которого
   * реестр писался.
   */
  traits: z.array(traitIdSchema),
});
export type MonsterSpec = z.infer<typeof monsterSpecSchema>;

/* ────────────────────── участки, уровень и отпирание ─────────────────── */

/** Сколько участков у каждой зоны. Схема требует ровно столько. */
export const SEGMENTS_PER_ZONE = 4;

/**
 * Границы участка, [мин, макс].
 *
 * ОДНА функция на весь репозиторий, как всё остальное про уровень:
 * карточка участка, старт забега, превью и бой обязаны брать одни
 * и те же числа. Второе место разошлось бы с первым на ближайшей
 * правке данных.
 */
export function segmentAt(
  zone: Pick<ZoneSpec, 'segments'>,
  segment: number,
): ZoneSpec['segments'][number] {
  const found = zone.segments[segment];
  if (found === undefined) throw new Error(`у зоны нет участка ${segment}`);
  return found;
}

/** Границы уровней участка, [мин, макс]. */
export function segmentBounds(
  zone: Pick<ZoneSpec, 'segments'>,
  segment: number,
): readonly [number, number] {
  return segmentAt(zone, segment).levels;
}

/**
 * Уровень врага. ОТ УЧАСТКА, а не от игрока.
 *
 * Уровень игрока сюда не передаётся, и это главное свойство функции,
 * а не деталь подписи. Прежняя формула `clamp(уровень игрока + сдвиг,
 * мин зоны, макс зоны)` вела зону за игроком: снаряжение оставалось
 * уровня, на котором добыто, а противники росли, и выхода средствами
 * игры не было (PLAYTEST 2026-09-04).
 *
 * СЛОЖНОСТЬ УРОВЕНЬ НЕ ДВИГАЕТ. Тир несёт множитель силы (§7.3
 * в редакции после M3b) — а после этой правки только его: смещение
 * уровня было одинаковым у всех трёх тиров ещё до неё, то есть уже
 * ничего не значило.
 *
 * Внутри участка уровень РАЗЫГРЫВАЕТСЯ броском, кроме боя с боссом:
 * участок 1-2 обязан ронять и ilvl 1, и ilvl 2, иначе «участок»
 * и «уровень» — одно и то же слово. Босс берёт верхнюю границу: он
 * последний бой участка, и быть слабее рядового ему не с чего.
 */
export function enemyLevel(
  zone: Pick<ZoneSpec, 'segments'>,
  segment: number,
  roll: number,
  isBoss: boolean,
): number {
  const [lo, hi] = segmentBounds(zone, segment);
  if (isBoss) return hi;
  const span = hi - lo + 1;
  return Math.min(hi, lo + Math.floor(Math.max(0, Math.min(0.999999, roll)) * span));
}

/**
 * Прогресс игрока по зоне: сколько участков пройдено (0..4).
 *
 * Участок считается пройденным, когда убит его босс, то есть пройдены
 * все пять боёв. Не «дошёл и эвакуировался»: эвакуация — это уход
 * с добычей вместо продолжения, и открывать ею следующий участок
 * значило бы платить продвижением за отказ от риска.
 */
export type ZoneProgress = Readonly<Record<string, number>>;

/**
 * Открыт ли участок. GDD §7.4 в редакции после тупика.
 *
 * ОТПИРАНИЕ ПРОХОЖДЕНИЕМ, А НЕ УРОВНЕМ ИГРОКА. Уровень игрока не
 * участвует нигде: прежний замок по уровню существовал затем, чтобы
 * переросший игрок не фармил «Кошмар» в первой зоне за полную цену,
 * — а это следствие того, что уровень врага ехал за игроком. Уровень
 * врага больше не едет, и замок остался бы без причины.
 *
 * ОДНА функция на весь репозиторий: карточка участка и вход в забег
 * обязаны отвечать одинаково. Замок только на карточке обходится одним
 * запросом мимо интерфейса — на этом уже стояли с зонами.
 */
export function isSegmentUnlocked(
  zones: readonly Pick<ZoneSpec, 'id'>[],
  progress: ZoneProgress,
  zoneId: string,
  segment: number,
): boolean {
  if (segment < 0 || segment >= SEGMENTS_PER_ZONE) return false;

  const at = zones.findIndex((zone) => zone.id === zoneId);
  if (at < 0) return false;

  /* Внутри зоны: пройденный участок открывает следующий. */
  if (segment > 0) return (progress[zoneId] ?? 0) >= segment;

  /* Первый участок первой зоны открыт всегда — иначе играть нечем.
     Первый участок следующей зоны открывает ПОЛНОСТЬЮ пройденная
     предыдущая: это то же правило, на уровень выше. */
  if (at === 0) return true;
  const previous = zones[at - 1];
  if (previous === undefined) return false;
  return (progress[previous.id] ?? 0) >= SEGMENTS_PER_ZONE;
}
