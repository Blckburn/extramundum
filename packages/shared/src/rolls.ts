/**
 * Бросок, выводимый из строки.
 *
 * Нужен там, где результат обязан НЕ ЗАВИСЕТЬ от того, сколько раз
 * игрок обновил экран: какой монстр в третьем бою, какие три карты
 * предложат на седьмом уровне. Общий генератор для этого не годится —
 * он зависит от порядка вызовов.
 *
 * ОДНА ФУНКЦИЯ НА ВЕСЬ РЕПОЗИТОРИЙ, и это не вкусовщина, а следствие
 * настоящей аварии. Приём был скопирован в два места — выбор монстра
 * в забеге и оффер драфта, — потом в ОДНОМ из них нашли ошибку
 * и починили, а второе осталось сломанным на три этапа. Комментарий
 * в починенном месте при этом ссылался на сломанное как на образец.
 *
 * ЛАВИНА ОБЯЗАТЕЛЬНА. FNV-1a заканчивается умножением, поэтому строки,
 * различающиеся ПОСЛЕДНИМ символом, дают хеши, различающиеся примерно
 * на множитель 0x01000193 — это 0.4% диапазона. А различаются последним
 * символом ровно те ключи, которые мы и подставляем: номер боя 0..3,
 * шаг оффера 0..2. Без лавины это один бросок, повторённый несколько
 * раз.
 *
 * Что это стоило, замерено (числа — в шапке `rolls.test.ts`):
 * 96.7% забегов шли против ОДНОГО И ТОГО ЖЕ монстра все четыре боя,
 * а дробный остаток лута срабатывал либо во всех пяти боях, либо
 * ни в одном.
 *
 * ПОЧЕМУ ЭТОГО НЕ ЗАМЕТИЛИ ТЕСТЫ: краевые доли были безупречны. Каждый
 * монстр выпадал в 33.3% боёв, остаток срабатывал в 24.7% случаев при
 * ожидании 25%. Сломана была не частота, а НЕЗАВИСИМОСТЬ соседних
 * бросков, и проверять надо именно её.
 */
export function seededRoll(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }

  // Лавина: размешивает низкие биты обратно в высокие.
  hash ^= hash >>> 16;
  hash = Math.imul(hash, 0x2545f491) >>> 0;
  hash ^= hash >>> 15;

  return (hash >>> 0) / 0x100000000;
}
