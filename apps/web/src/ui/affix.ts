import { isPercentFamily, type ItemAffix } from '@extramundum/shared';

import { t } from '../i18n.ts';

/**
 * Текст аффикса. ОДНА функция на весь клиент.
 *
 * Текст берётся по КЛЮЧУ СЕМЕЙСТВА (`affix.<family>`), а не ветвлением
 * по каждому из семи: забытая ветка молча превратилась бы в строку
 * другого семейства, и игрок прочитал бы «+12% урона» там, где надет
 * «+12% брони». Отсутствующий ключ ловит тест локалей.
 *
 * Проценты показываются процентами, плоские — единицами: одно и то же
 * число в двух видах — это пункт 4 аудита v1.0. Правило живёт здесь,
 * а не в каждом экране, потому что экранов с аффиксами стало два —
 * снаряжение и кузнец, — и вторая копия разошлась бы с первой молча.
 */
export function affixText(affix: Pick<ItemAffix, 'family' | 'value'>): string {
  return t(`affix.${affix.family}`, {
    value: isPercentFamily(affix.family) ? Math.round(affix.value * 1000) / 10 : affix.value,
  });
}
