import { describe, expect, it } from 'vitest';

import { overridden, RULES } from './css.ts';

/**
 * НИ ОДНО ПРАВИЛО НЕ ПЕРЕКРЫТО МОЛЧА.
 *
 * За один заход перекрытое правило поймали дважды: `.button--small`
 * был объявлен в файле два раза с разными отступами, а `gap`
 * у `.inv__grid` перебивал общий — и браузер показывал 5.6 пикселя
 * там, где тест по исходнику видел восемь.
 *
 * Оба раза проверка «правило есть» была ЗЕЛЁНОЙ. Она и не могла
 * поймать: перекрытое правило в файле присутствует, просто
 * не действует. Проверять надо, что оно ПОБЕЖДАЕТ.
 *
 * Проверка строгая по умолчанию. Намеренная специализация («группа
 * задаёт умолчание, отдельный селектор его уточняет») формой
 * не отличается от случайного дубля — отличается только замыслом,
 * а замысел в CSS не выражается. Поэтому замысел записывается сюда
 * списком: чтобы добавить перекрытие, надо дописать строку и объяснить
 * её. Эта же строка — то трение, из-за которого случайный дубль
 * становится видно.
 */
const DELIBERATE: { selector: string; prop: string; why: string }[] = [
  {
    selector: '.button--ghost',
    prop: 'border-color',
    why: 'группа `--link, --ghost` снимает рамку у обоих, затем `--ghost` возвращает её себе',
  },
];

describe('каскад стилей', () => {
  it('разбор нашёл правила, а не пустоту', () => {
    /* Пара к проверке ниже. Сломанный разбор даёт ноль правил, ноль
       перекрытий и зелёный тест — то есть ровно ту тишину, ради
       которой всё это и написано. Так уже было: первая редакция
       спотыкалась о `@media` и находила 115 правил вместо 240. */
    expect(RULES.length).toBeGreaterThan(150);
    expect(RULES.some((r) => r.conditional)).toBe(true);
  });

  it('одно свойство одного селектора объявлено один раз', () => {
    const allowed = new Set(DELIBERATE.map((x) => `${x.selector} ${x.prop}`));
    const unexpected = overridden().filter((x) => !allowed.has(`${x.selector} ${x.prop}`));

    expect(unexpected, 'перекрытые правила: первое выглядит действующим и не действует').toEqual(
      [],
    );
  });

  it('в списке исключений нет протухших записей', () => {
    /* Исключение, которое больше ничего не разрешает, — это забытый
       комментарий, и через месяц по нему нельзя понять, чего боялись.
       Оно обязано исчезать вместе с причиной. */
    const real = new Set(overridden().map((x) => `${x.selector} ${x.prop}`));
    for (const item of DELIBERATE) {
      expect(
        real.has(`${item.selector} ${item.prop}`),
        `исключение «${item.selector} ${item.prop}» больше ничего не разрешает`,
      ).toBe(true);
    }
  });

  it('у каждого исключения записана причина', () => {
    for (const item of DELIBERATE) {
      expect(item.why.length, `${item.selector} ${item.prop} без причины`).toBeGreaterThan(20);
    }
  });
});
