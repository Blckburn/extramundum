import { paletteColor } from '@extramundum/data';

/**
 * Цвет палитры как ЧИСЛО, посчитанное один раз.
 *
 * Нужен ровно затем, чтобы не аллоцировать в бою. `Color.set('#6b2621')`
 * разбирает строку регулярным выражением, а `exec` создаёт массив
 * совпадений — то есть каждый всплеск искр отдавал работу сборщику
 * мусора ровно в момент удара. Замер поймал это как 18 байт на кадр
 * при заявленном нуле; после перевода на `setHex` стало ноль.
 *
 * Разбор происходит при ПЕРВОМ обращении к ключу и больше никогда:
 * ключей полтора десятка, и все встречаются в первую секунду боя.
 * Отдельный кэш, а не поле в данных, потому что число нужно только
 * рендеру: `palette.json` описывает цвет, а не его представление
 * в памяти three.
 */
const cache = new Map<string, number>();

export function paletteHex(key: string): number {
  const cached = cache.get(key);
  if (cached !== undefined) return cached;

  // `paletteColor` уже падает на неизвестном ключе — здесь ничего
  // не подставляется молча.
  const parsed = Number.parseInt(paletteColor(key).slice(1), 16);
  cache.set(key, parsed);
  return parsed;
}
