import { itemBase } from '@extramundum/data';

import type { Database } from '../db/client.ts';
import { equipment, items } from '../db/schema/items.ts';

/**
 * Стартовое оружие. GDD §5.1.
 *
 * ПОЧЕМУ ЭТО НЕ «НАБОР РАЗРАБОТКИ» И НЕ ЗА ФЛАГОМ. Замерено в M3b:
 * с голыми кулаками игрок первого уровня выигрывает у монстров Пустошей
 * 0% боёв — у всех трёх и у босса. С обычным мечом того же уровня —
 * 94 / 100 / 100% и 86% у босса. Разница не в балансе, а в наличии
 * входа в игру: без оружия петля рейда не начинается вовсе.
 *
 * Числа кулаков жалкие НАМЕРЕННО (balance.unarmed: «голые кулаки
 * не должны выглядеть рабочим билдом»), и §5.1 прямо называет стартовое
 * оружие одним из трёх выборов при создании персонажа. То есть это
 * не поблажка, а недостающая часть документа.
 *
 * ЧЕГО ЗДЕСЬ ПОКА НЕТ: самого выбора. §5.1 говорит «оружие из класса,
 * доступного причине изгнания», но причина изгнания в базе не хранится
 * и экрана создания персонажа не существует — это отдельная работа.
 * Поэтому выдаётся ОДИН нейтральный сбалансированный клинок: он никого
 * не ставит в матчапе §4.3 в выигрышное положение заранее.
 *
 * НАПРЯЖЕНИЕ С ЛОРОМ НАЗВАНО, А НЕ СПРЯТАНО. LORE §2: изгнанного
 * выводят за ворота ни с чем. Здесь он получает клинок — самый дешёвый,
 * обычной редкости, первого уровня. Вопрос к человеку: считать его
 * подобранным сразу за стеной или править §5.1.
 */

/** Нейтральная база: сбалансированный класс, самый дешёвый вариант. */
const STARTING_WEAPON_KEY = 'weapon.sword';

/**
 * Выдать и НАДЕТЬ стартовое оружие.
 *
 * Надеть обязательно: предмет, лежащий в сумке, от кулаков не спасает,
 * а первый экран игры — не инвентарь. Обе записи в одной транзакции —
 * предмет без строки в `equipment` был бы наполовину выданным.
 */
export async function grantStartingWeapon(db: Database, playerId: string): Promise<void> {
  // База обязана существовать: неизвестный ключ — ошибка данных,
  // и `itemBase` на ней падает, а не выдаёт пустой предмет.
  const base = itemBase(STARTING_WEAPON_KEY);

  await db.transaction(async (tx) => {
    const [row] = await tx
      .insert(items)
      .values({
        ownerId: playerId,
        baseKey: base.key,
        ilvl: 1,
        rarity: 'common',
        // Обычная редкость — ноль аффиксов (GDD §6.2). Это именно то,
        // что нужно: стартовое оружие не должно опережать первый лут.
        affixes: [],
        container: 'equipped',
      })
      .returning({ id: items.id });

    if (row === undefined) throw new Error('стартовое оружие не записано');

    await tx
      .insert(equipment)
      .values({ playerId, slot: base.slot, itemId: row.id })
      .onConflictDoUpdate({
        target: [equipment.playerId, equipment.slot],
        set: { itemId: row.id },
      });
  });
}
