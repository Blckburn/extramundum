--
-- ДОБИВКА ПРОФИЛЕЙ ЭПОХИ M0. Найдено по жалобе игрока, а не тестом.
--
-- Симптом со стороны игрока: «за весь бой я бью один раз, вся инициатива
-- за врагом». Формулы боя при этом верны — замерено: свежий изгнанный
-- с нынешними статами берёт 14 ходов против 11 у монстра. Причина
-- в профиле, созданном до M3b: он не получил НИЧЕГО из трёх вещей,
-- которые с тех пор выдаются при регистрации.
--
--   статы          остались умолчаниями схемы 5/5/5/5 вместо 12/13/13/13
--   базовая броня   ноль (колонки появились миграцией 0006)
--   оружие          нет вовсе (клинок у ворот появился в M3b)
--
-- Что это давало в бою, замерено на монстрах Пустошей:
--   SPD 5 против SPD 10–13 — враг действует ВДВОЕ-ВТРОЕ чаще,
--   ходов игрока 3–5 против 7–12 у врага,
--   урона 6–13 против 99–113 по игроку. Гарантированная смерть.
--
-- Добивка идёт ТОЛЬКО по подписи M0: ровно 5/5/5/5 и первый уровень.
-- Настоящий профиль после M3b имеет 12/13/13/13, а прокачанный —
-- уровень выше первого. Условие узкое намеренно: молча переписать
-- статы живому игроку хуже, чем не починить старый профиль.
--
UPDATE "players" SET
  "stat_atk" = 12,
  "stat_def" = 13,
  "stat_agi" = 13,
  "stat_spd" = 13,
  -- HP пересчитывается под новый DEF: 60 + 13 × 6 + 14 = 152.
  -- Игрок при этом не «лечится» сверх максимума — он им и был зажат.
  "hp_current" = 152
WHERE "stat_atk" = 5 AND "stat_def" = 5 AND "stat_agi" = 5 AND "stat_spd" = 5
  AND "level" = 1;--> statement-breakpoint
--
-- КЛИНОК У ВОРОТ тем, у кого нет ни одного предмета. §5.1.
--
-- Условие «ни одного предмета» — не «нет оружия»: игрок, продавший
-- всё до последнего, оказался бы в том же тупике, а игрок с полным
-- инвентарём и пустым слотом оружия сам решил его снять, и лезть
-- к нему незачем.
--
INSERT INTO "items" ("owner_id", "container", "base_key", "ilvl", "rarity", "affixes")
SELECT p."id", 'equipped', 'weapon.sword', 1, 'common', '[]'::jsonb
FROM "players" p
WHERE NOT EXISTS (SELECT 1 FROM "items" i WHERE i."owner_id" = p."id");--> statement-breakpoint
--
-- И сразу НА ПОЯС: предмет, лежащий в сумке, от кулаков не спасает,
-- а первый экран игры — не инвентарь.
--
INSERT INTO "equipment" ("player_id", "slot", "item_id")
SELECT i."owner_id", 'weapon', i."id"
FROM "items" i
WHERE i."base_key" = 'weapon.sword'
  AND i."container" = 'equipped'
  AND NOT EXISTS (
    SELECT 1 FROM "equipment" e WHERE e."player_id" = i."owner_id" AND e."slot" = 'weapon'
  );
